import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.argv[2]||'playwright');
const url=process.argv[3]||'http://127.0.0.1:8086';
const browser=await chromium.launch({channel:'msedge',headless:true});
const screenshotDir='research/ucl-history';
const errors=[];
try{
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  await context.route('**/*',route=>{
    const u=new URL(route.request().url());
    if(u.hostname==='127.0.0.1')return route.continue();
    return route.abort();
  });
  const page=await context.newPage();
  page.on('pageerror',error=>errors.push(error.message));
  await page.clock.setFixedTime(new Date('2026-10-14T08:00:00Z'));
  await page.goto(url+'/?season=2026-27');
  await page.locator('#predictorBtn').click();
  await page.locator('.predictor-matchup').waitFor();
  const original=await page.evaluate(()=>window.UclPredictorPage.getForecast());
  assert.ok(original.prediction.trainingGames>=864);
  const shown=await page.locator('.predictor-bars strong').allTextContents();
  assert.equal(shown.reduce((n,s)=>n+Number.parseFloat(s),0),100);
  await page.locator('#predictorRound').selectOption('3');
  await page.waitForFunction(()=>document.querySelector('#predictorFixtureCount').textContent.startsWith('18 场'));
  await page.locator('#predictorSearch').fill('巴黎');
  await page.waitForFunction(()=>document.querySelector('#predictorFixtureCount').textContent.startsWith('1 场'));
  const selected=await page.evaluate(()=>window.UclPredictorPage.getForecast());
  assert.equal(selected.fixture.home==='Paris Saint-Germain'||selected.fixture.away==='Paris Saint-Germain',true);
  await page.locator('#predictorOpenDetail').click();
  await page.locator('.prediction-row input[data-field="note"]').fill('浏览器验证：个人预测保留');
  await page.locator('.prediction-save').click();
  await page.locator('#close').click();
  await page.waitForFunction(()=>document.querySelector('.predictor-manual')?.textContent.includes('个人预测保留'));
  const before=await page.evaluate(()=>window.UclPredictorPage.getForecast());
  await page.evaluate(()=>{
    const current=window.UclPredictorPage.getForecast().fixture;
    const opponent=current.home==='Liverpool'?'Manchester City':'Liverpool';
    matches.push(['2026-10-12',current.home,opponent,'3-0','1-0','league']);
    window.dispatchEvent(new Event('ucl:data-updated'));
  });
  await page.waitForFunction(n=>window.UclPredictorPage.getForecast()?.prediction.trainingGames>n,before.prediction.trainingGames);
  const after=await page.evaluate(()=>window.UclPredictorPage.getForecast());
  assert.notEqual(before.prediction.result.home,after.prediction.result.home);
  await page.locator('#predictorSearch').fill('不存在球队');
  await page.waitForFunction(()=>document.querySelector('#predictorFixtureCount').textContent.startsWith('0 场'));
  assert.match(await page.locator('#predictorOutput').textContent(),/没有可预测/);
  await page.locator('#predictorSearch').fill('');
  await page.locator('#predictorRound').selectOption('all');
  await page.locator('.predictor-matchup').waitFor();
  await page.evaluate(()=>localStorage.removeItem('ucl36-match-predictions-v1-2026-27'));
  await page.goto(url+'/?season=2026-27&view=predictor');
  await page.locator('.predictor-matchup').waitFor();
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await fs.mkdir(screenshotDir,{recursive:true});
  await page.screenshot({path:screenshotDir+'/predictor-desktop.png',fullPage:true});
  await page.screenshot({path:screenshotDir+'/predictor-desktop-top.png'});
  await page.locator('[data-predictor-view="backtest"]').click();
  assert.match(await page.locator('#predictorBacktestOutput').textContent(),/288 场/);
  await page.locator('#predictorTestSeason').selectOption('2024-25');
  assert.match(await page.locator('#predictorBacktestOutput').textContent(),/144 场/);
  await page.locator('#predictorTestSeason').selectOption('all');
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await page.screenshot({path:screenshotDir+'/predictor-backtest.png',fullPage:true});
  await page.screenshot({path:screenshotDir+'/predictor-backtest-top.png'});
  await page.locator('[data-predictor-view="forecast"]').click();
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  const width=await page.evaluate(()=>document.documentElement.scrollWidth);
  assert.ok(width<=391,'Mobile page overflow: '+width);
  await page.screenshot({path:screenshotDir+'/predictor-mobile.png',fullPage:true});
  await page.locator('#scheduleBtn').click();
  assert.equal(await page.locator('#predictorPage').evaluate(el=>el.classList.contains('active')),false);
  assert.equal(await page.locator('#schedulePage').evaluate(el=>el.classList.contains('active')),true);
  await page.locator('#predictorBtn').click();
  await page.locator('.predictor-matchup').waitFor();
  for(const season of ['2024-25','2025-26']){
    await page.goto(url+'/?season='+season);await page.locator('#predictorBtn').click();
    await page.locator('.predictor-metrics').waitFor();
    assert.equal(await page.locator('#predictorTestSeason').inputValue(),season);
    assert.match(await page.locator('#predictorBacktestOutput').textContent(),/144 场/);
    assert.equal(await page.locator('.predictor-matchup').count(),0);
  }
  await page.goto(url+'/?season=2026-27');
  await page.locator('#predictorBtn').click();
  await page.locator('.predictor-matchup').waitFor();
  for(const id of ['latestBtn','infoBtn','qualificationBtn','advancementBtn']){
    await page.locator('#'+id).click();
    assert.equal(await page.locator('#predictorPage').evaluate(el=>el.classList.contains('active')),false);
    await page.locator('#predictorBtn').click();
    await page.locator('.predictor-matchup').waitFor();
  }
  let failModel=true;
  await context.route('**/js/data/prediction/model.json',route=>failModel?route.fulfill({status:503,body:'Model temporarily unavailable'}):route.continue());
  await page.goto(url+'/?season=2026-27&view=predictor');
  await page.locator('#predictorRetry').waitFor();
  failModel=false;await page.locator('#predictorRetry').click();
  await page.locator('.predictor-matchup').waitFor();
  assert.deepEqual(errors,[]);
  console.log('PASS: predictions, matchday/search filters, rounded probabilities, manual storage, refresh recalculation, mobile layout, navigation, and three seasons.');
  await context.close();
}finally{await browser.close()}
