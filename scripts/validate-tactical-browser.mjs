import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.argv[2] || 'playwright');
const url = process.argv[3] || 'http://127.0.0.1:8086';
const browser = await chromium.launch({channel:'msedge', headless:true});
const errors = [];
try {
  const context = await browser.newContext({viewport:{width:1440,height:1050}});
  await context.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.clock.setFixedTime(new Date('2026-10-15T01:00:00Z'));
  await page.goto(url + '/?season=2026-27&view=predictor&tab=tactics');
  await page.locator('.tactics-profile-hero').waitFor();
  assert.equal(await page.locator('[data-tactics-club]').count(), 36);
  assert.equal(await page.locator('#predictorForecast').isVisible(), false);
  const ids = await page.locator('[data-tactics-club]').evaluateAll(elements => elements.map(element => element.dataset.tacticsClub));
  for (const id of ids) {
    await page.locator('[data-tactics-club="' + id + '"]').click();
    assert.ok((await page.locator('.tactics-profile-name h3').textContent()).trim());
    assert.ok(await page.locator('.tactics-sources a').count() >= 1);
    assert.ok(await page.locator('.tactics-scenarios .tactics-scenario').count() >= 2);
  }
  await page.locator('#tacticsSearch').fill('巴黎');
  assert.equal(await page.locator('[data-tactics-club]').count(), 1);
  await page.locator('[data-tactics-club="paris-saint-germain"]').click();
  assert.match(await page.locator('.tactics-profile-name').textContent(), /巴黎圣日耳曼/);
  await page.locator('#tacticsOpponent').selectOption('arsenal');
  assert.match(await page.locator('.tactics-opponent').textContent(), /阿森纳/);
  await page.locator('[data-tactics-swap]').click();
  assert.match(await page.locator('.tactics-profile-name').textContent(), /阿森纳/);
  await page.locator('#tacticsSearch').fill('');
  await page.locator('#tacticsDimension').selectOption('restDefence');
  assert.ok(await page.locator('[data-tactics-club]').count() < 36);
  await page.locator('#tacticsDimension').selectOption('all');
  await page.locator('[data-tactics-section="mechanisms"]').click();
  assert.equal(await page.locator('#tacticsMechanisms>.tactics-scenario').count(), 14);
  await page.locator('#tacticsStyle').selectOption('high-press');
  assert.ok(await page.locator('#tacticsMechanisms>.tactics-scenario').count() < 14);
  await page.locator('[data-tactics-section="dictionary"]').click();
  assert.equal(await page.locator('.tactics-dictionary>article').count(), 11);
  await page.locator('[data-predictor-view="forecast"]').click();
  await page.locator('.predictor-matchup').waitFor();
  const before = await page.evaluate(() => JSON.stringify(window.UclPredictorPage.getForecast().prediction));
  const selected = await page.evaluate(() => window.UclPredictorPage.getForecast().fixture);
  await page.locator('#predictorOpenTactics').click();
  await page.waitForFunction(name => window.UclTacticsPage.getCatalog().get(new URL(location.href).searchParams.get('club')).name === name, selected.home);
  assert.equal(await page.locator('.tactics-opponent').count(), 1);
  await page.locator('[data-predictor-view="forecast"]').click();
  const after = await page.evaluate(() => JSON.stringify(window.UclPredictorPage.getForecast().prediction));
  assert.equal(after, before);
  await page.goto(url + '/?season=2026-27&view=predictor&tab=tactics&club=paris-saint-germain&opponent=arsenal');
  await page.locator('.tactics-profile-hero').waitFor();
  await fs.mkdir('research/ucl-history', {recursive:true});
  await page.evaluate(() => window.scrollTo({top:0,behavior:'instant'}));
  await page.screenshot({path:'research/ucl-history/tactics-desktop.png',fullPage:true});
  await page.screenshot({path:'research/ucl-history/tactics-desktop-top.png'});
  await page.locator('.tactics-profile-hero').scrollIntoViewIfNeeded();
  await page.screenshot({path:'research/ucl-history/tactics-desktop-profile.png'});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth) <= 391);
  await page.locator('.tactics-profile-hero').scrollIntoViewIfNeeded();
  await page.screenshot({path:'research/ucl-history/tactics-mobile.png'});
  await page.locator('[data-tactics-section="mechanisms"]').click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth) <= 391);
  await page.goto(url + '/?season=2025-26&view=predictor&tab=tactics');
  await page.locator('.predictor-metrics').waitFor();
  assert.equal(await page.locator('[data-predictor-view="tactics"]').isDisabled(), true);
  assert.equal(await page.locator('#predictorTactics').isVisible(), false);
  let fail = true;
  await context.route('**/js/data/tactics/clubs-c.json', route => fail ? route.fulfill({status:503,body:'Unavailable'}) : route.continue());
  await page.goto(url + '/?season=2026-27&view=predictor&tab=tactics');
  await page.locator('[data-tactics-retry]').waitFor();
  fail = false; await page.locator('[data-tactics-retry]').click();
  await page.locator('.tactics-profile-hero').waitFor();
  assert.equal(await page.locator('[data-tactics-club]').count(), 36);
  assert.deepEqual(errors, []);
  await context.close();
  console.log('PASS: all 36 dossiers, sources, search, dimension filters, opponent swap, 14 mechanisms, dictionary, forecast isolation, mobile, archives and retry.');
} finally { await browser.close(); }
